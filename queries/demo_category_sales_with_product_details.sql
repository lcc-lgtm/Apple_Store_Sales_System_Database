SET PAGESIZE 150
SET LINESIZE 200

CLEAR BREAKS
CLEAR COMPUTES
CLEAR COLUMNS

cl scr
ACCEPT start_date CHAR PROMPT 'Start date (DD-MON-YYYY): '
ACCEPT end_date CHAR PROMPT 'End date (DD-MON-YYYY): '

cl scr
TTITLE CENTER 'CATEGORY SALES WITH PRODUCT DETAILS' SKIP 1 -
       LEFT 'Period: &start_date to &end_date' RIGHT 'Page:' SQL.PNO SKIP 2

COLUMN CATEGORY_NAME HEADING 'Category' FORMAT A25
COLUMN PRODUCT_NAME HEADING 'Product Name' FORMAT A40
COLUMN UNITS_SOLD HEADING 'Units|Sold' FORMAT 9,999
COLUMN PRODUCT_SALES HEADING 'Product|Sales' FORMAT $999,999.99
COLUMN CATEGORY_TOTAL HEADING 'Category|Total' FORMAT $999,999.99

BREAK ON CATEGORY_NAME SKIP 1 ON REPORT
COMPUTE SUM OF PRODUCT_SALES ON CATEGORY_NAME
COMPUTE SUM OF PRODUCT_SALES ON REPORT
COMPUTE SUM OF UNITS_SOLD ON CATEGORY_NAME
COMPUTE SUM OF UNITS_SOLD ON REPORT

cl scr
SELECT
    C.CATEGORY_NAME,
    P.PRODUCT_NAME,
    SUM(OL.quantity) AS UNITS_SOLD,
    SUM(OL.SUB_TOTAL) AS PRODUCT_SALES,
    (SELECT SUM(OL2.SUB_TOTAL)
     FROM ORDERS_LIST OL2
     JOIN PRODUCT P2 ON OL2.PRODUCT_ID = P2.PRODUCT_ID
     JOIN ORDERS O2 ON OL2.ORDERS_ID = O2.ORDERS_ID
     JOIN PAYMENT PY2 ON O2.ORDERS_ID = PY2.ORDER_ID
     WHERE P2.CATEGORY_ID = C.CATEGORY_ID
       AND PY2.STATUS = 'Success'
       AND O2.ORDERS_DATE BETWEEN TO_DATE('&start_date', 'DD-MON-YYYY')
                             AND TO_DATE('&end_date', 'DD-MON-YYYY')) AS CATEGORY_TOTAL
FROM CATEGORY C
JOIN PRODUCT P ON C.CATEGORY_ID = P.CATEGORY_ID
JOIN ORDERS_LIST OL ON P.PRODUCT_ID = OL.PRODUCT_ID
JOIN ORDERS O ON OL.ORDERS_ID = O.ORDERS_ID
JOIN PAYMENT PY ON O.ORDERS_ID = PY.ORDER_ID
WHERE PY.STATUS = 'Success'
    AND O.ORDERS_DATE BETWEEN TO_DATE('&start_date', 'DD-MON-YYYY')
                          AND TO_DATE('&end_date', 'DD-MON-YYYY')
GROUP BY C.CATEGORY_NAME, P.PRODUCT_NAME, C.CATEGORY_ID
ORDER BY C.CATEGORY_NAME, PRODUCT_SALES DESC;
